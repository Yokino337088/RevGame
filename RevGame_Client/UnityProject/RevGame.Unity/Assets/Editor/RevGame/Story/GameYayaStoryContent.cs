        private static StoryBook.Episode Episode(string id, string title, int background, params string[] text)
        {
            var lines = new StoryBook.Line[text.Length];
            for (int i = 0; i < text.Length; i++)
            {
                string[] fields = text[i].Split(new[] { '|' }, 3);
                lines[i] = new StoryBook.Line { Expression = int.Parse(fields[0]), Speaker = fields[1], Text = fields[2] };
            }
            return new StoryBook.Episode { Id = id, Title = title, BackgroundChapter = background, Lines = lines };
        }
