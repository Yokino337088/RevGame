        private static StoryBook.Episode Episode(string id, string title, params string[] text)
        {
            var lines = new StoryBook.Line[text.Length];
            for (int i = 0; i < text.Length; i++)
            {
                int split = text[i].IndexOf('|');
                lines[i] = new StoryBook.Line { Speaker = text[i].Substring(0, split), Text = text[i].Substring(split + 1) };
            }
            return new StoryBook.Episode { Id = id, Title = title, Lines = lines };
        }

